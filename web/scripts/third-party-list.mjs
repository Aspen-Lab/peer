#!/usr/bin/env node
// Keeps the npm part of docs/THIRD_PARTY_NOTICES.md in step with
// web/package-lock.json.
//
// WHY THIS EXISTS: the owners' co-ownership agreement (Section 4.4) asks for a
// record of every third-party component in Peer and its license. The lockfile
// already names every installed package; this script turns it into the table
// between the two markers in the notices file, so the record is regenerated
// rather than typed by hand.
//
//   node scripts/third-party-list.mjs           prints the generated section
//   node scripts/third-party-list.mjs --write   rewrites it in the notices file
//   node scripts/third-party-list.mjs --check   exits 1 if the file is out of date
//
// Run from web/. Reads two local files and writes at most one; no network.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lockPath = path.join(webDir, "package-lock.json");
const noticesPath = path.join(webDir, "..", "docs", "THIRD_PARTY_NOTICES.md");

const START = "<!-- npm-packages:start (generated by web/scripts/third-party-list.mjs; do not edit by hand) -->";
const END = "<!-- npm-packages:end -->";

function licenseOf(entry) {
  const raw = entry.license ?? entry.licenses;
  if (!raw) return "not stated in the lockfile";
  if (typeof raw === "string") return raw;
  if (Array.isArray(raw)) return raw.map((l) => (typeof l === "string" ? l : l.type)).join(" OR ");
  return raw.type ?? "not stated in the lockfile";
}

function scopeOf(entry) {
  if (entry.dev || entry.devOptional) return "development";
  if (entry.optional) return "runtime (optional)";
  return "runtime";
}

function buildRows(lock) {
  const rows = new Map();
  for (const [key, entry] of Object.entries(lock.packages ?? {})) {
    if (!key || entry.link) continue;
    const name = entry.name ?? key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
    const row = { name, version: entry.version ?? "", license: licenseOf(entry), scope: scopeOf(entry) };
    const id = `${row.name}@${row.version}`;
    const seen = rows.get(id);
    // The same package can sit in several places in the tree; runtime wins.
    if (!seen || (seen.scope === "development" && row.scope !== "development")) rows.set(id, row);
  }
  return [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function render(rows) {
  const runtime = rows.filter((r) => r.scope !== "development").length;
  const byLicense = new Map();
  for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);
  const summary = [...byLicense.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

  return [
    START,
    "",
    `Generated from \`web/package-lock.json\`: ${rows.length} packages, ${runtime} used when the app runs and ${rows.length - runtime} used only for development and tests.`,
    "",
    "| License | Packages |",
    "|---|---|",
    ...summary.map(([license, count]) => `| ${license} | ${count} |`),
    "",
    "| Package | Version | License | Used for |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.scope} |`),
    "",
    END,
  ].join("\n");
}

function replaceSection(text, section) {
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`docs/THIRD_PARTY_NOTICES.md has no generated section; add the two marker lines:\n${START}\n${END}`);
  }
  return text.slice(0, start) + section + text.slice(end + END.length);
}

const section = render(buildRows(JSON.parse(fs.readFileSync(lockPath, "utf8"))));
const mode = process.argv[2];

if (mode === "--write" || mode === "--check") {
  const original = fs.readFileSync(noticesPath, "utf8");
  const crlf = original.includes("\r\n");
  const current = original.replace(/\r\n/g, "\n");
  const updated = replaceSection(current, section);
  if (mode === "--check") {
    if (updated !== current) {
      console.error("docs/THIRD_PARTY_NOTICES.md is out of date with web/package-lock.json.");
      console.error("Run `node scripts/third-party-list.mjs --write` from web/ and commit the result.");
      process.exit(1);
    }
    console.log("docs/THIRD_PARTY_NOTICES.md matches web/package-lock.json.");
  } else {
    fs.writeFileSync(noticesPath, crlf ? updated.replace(/\n/g, "\r\n") : updated);
    console.log("Rewrote the npm section of docs/THIRD_PARTY_NOTICES.md.");
  }
} else {
  console.log(section);
}
